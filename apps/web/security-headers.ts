// Security headers of the web app (T-28, docs/07-security.md → «XSS»). `vite preview` sends them
// (Playwright and the ZAP baseline run against it); in production Caddy sends the same: the
// build writes them as a Caddyfile snippet (`caddyHeaderBlock`, T-30).
// Not for `vite dev`: its HMR client and React refresh need inline scripts.

/** `tileOrigin` — map tiles (react-leaflet); the service worker also fetches them (`connect-src`). */
const contentSecurityPolicy = (tileOrigin: string) => ({
  'default-src': ["'self'"],
  // Bundled scripts only: no inline script, no eval.
  'script-src': ["'self'"],
  // Inline styles stay allowed: libraries insert <style> tags (Leaflet, scroll lock of dialogs).
  // A style cannot run code; the scripts above are what XSS needs.
  'style-src': ["'self'", "'unsafe-inline'"],
  // `data:` — the QR code and Leaflet icons; `blob:` — photos fetched with the token.
  'img-src': ["'self'", 'data:', 'blob:', tileOrigin],
  'font-src': ["'self'"],
  // The API is on the same origin (/api is proxied).
  'connect-src': ["'self'", tileOrigin],
  'worker-src': ["'self'"],
  'manifest-src': ["'self'"],
  'object-src': ["'none'"],
  'base-uri': ["'self'"],
  'form-action': ["'self'"],
  // No framing of the app (clickjacking of «Zapłać», «Unieważnij»).
  'frame-ancestors': ["'none'"],
});

/** The headers of every page and file of the app, for tiles served from `tileOrigin`. */
export const securityHeaders = (tileOrigin: string): Readonly<Record<string, string>> => ({
  'Content-Security-Policy': Object.entries(contentSecurityPolicy(tileOrigin))
    .map(([directive, sources]) => `${directive} ${sources.join(' ')}`)
    .join('; '),
  'X-Content-Type-Options': 'nosniff',
  // Email links carry one-time tokens in the URL (also the <meta> in index.html).
  'Referrer-Policy': 'no-referrer',
  'X-Frame-Options': 'DENY',
  // The catch and inspection forms ask for the position; nothing else is used.
  'Permissions-Policy': 'geolocation=(self), camera=(), microphone=(), payment=()',
  'Cross-Origin-Opener-Policy': 'same-origin',
  // Our files are for our pages only (Spectre isolation; COEP would block the OSM tiles).
  'Cross-Origin-Resource-Policy': 'same-origin',
});

/**
 * The same headers as a Caddy `header` block (imported by the Caddyfile of the web image).
 * `-Server` drops the header naming the server software, as `vite preview` does not send it.
 */
export function caddyHeaderBlock(headers: Readonly<Record<string, string>>): string {
  const lines = Object.entries(headers).map(([name, value]) => {
    if (!/^[A-Za-z-]+$/.test(name) || /[\r\n]/.test(value)) {
      throw new Error(`Header cannot be written to the Caddyfile: ${name}`);
    }
    return `\t${name} "${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
  });
  return [
    '# Generated by `vite build` from security-headers.ts: do not edit.',
    'header {',
    ...lines,
    '\t-Server',
    '}',
    '',
  ].join('\n');
}
